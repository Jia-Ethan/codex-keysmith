def test_cli_check_and_set_round_trip(tmp_path, capsys):
    _repo_fixture(tmp_path)

    assert bump_version.main(["--root", str(tmp_path), "check"]) == 0
    assert json.loads(capsys.readouterr().out) == {"version": "0.4.0"}

    assert bump_version.main(["--root", str(tmp_path), "set", "0.5.0"]) == 0
    assert json.loads(capsys.readouterr().out)["version"] == "0.5.0"

    assert bump_version.main(["--root", str(tmp_path), "check"]) == 0
    assert json.loads(capsys.readouterr().out) == {"version": "0.5.0"}


def test_cli_reports_failure_without_a_traceback(tmp_path, capsys):
    _repo_fixture(tmp_path)

    assert bump_version.main(["--root", str(tmp_path), "set", "nope"]) == 1

    captured = capsys.readouterr()
    assert captured.out == ""
    assert "version bump failed" in captured.err
