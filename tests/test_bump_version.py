import json
import re
from pathlib import Path

import pytest

from scripts import bump_version
from scripts import validate_desktop_candidate as validator

REPO_ROOT = Path(__file__).resolve().parents[1]


def _repo_fixture(root: Path, version: str = "0.4.0") -> None:
    """Materialize only the files bump_version rewrites."""
    (root / "gui/src-tauri").mkdir(parents=True, exist_ok=True)
    (root / "VERSION").write_text(f"{version}\n", encoding="utf-8")
    (root / "codex-instruct.py").write_text(
        f'#!/usr/bin/env python3\n__version__ = "{version}"\nVERSION = __version__\n',
        encoding="utf-8",
    )
    (root / "gui/package.json").write_text(
        json.dumps(
            {"name": "codex-keysmith-gui", "private": True, "version": version},
            indent=2,
        )
        + "\n",
        encoding="utf-8",
    )
    (root / "gui/package-lock.json").write_text(
        json.dumps(
            {
                "name": "codex-keysmith-gui",
                "version": version,
                "lockfileVersion": 3,
                "packages": {
                    "": {"name": "codex-keysmith-gui", "version": version},
                    "node_modules/left-pad": {"version": "1.3.0"},
                },
            },
            indent=2,
        )
        + "\n",
        encoding="utf-8",
    )
    (root / "gui/src-tauri/Cargo.toml").write_text(
        "[package]\n"
        "name = \"codex-keysmith-gui\"\n"
        f'version = "{version}"\n'
        'edition = "2021"\n'
        "\n"
        "[dependencies]\n"
        'serde = "1"\n',
        encoding="utf-8",
    )
    (root / "gui/src-tauri/Cargo.lock").write_text(
        "# This file is automatically @generated by Cargo.\n"
        "version = 4\n"
        "\n"
        "[[package]]\n"
        'name = "codex-keysmith-gui"\n'
        f'version = "{version}"\n'
        "dependencies = [\n"
        ' "serde",\n'
        "]\n"
        "\n"
        "[[package]]\n"
        'name = "winapi"\n'
        'version = "0.3.9"\n'
        'source = "registry+https://github.com/rust-lang/crates.io-index"\n',
        encoding="utf-8",
    )


def test_repository_source_versions_are_synchronized():
    """The real tree must never ship a partial version bump (regression for PR #68)."""
    versions = bump_version.read_versions(REPO_ROOT)

    assert set(versions) == set(bump_version.VERSION_FILES)
    assert len(set(versions.values())) == 1, versions
    assert versions["VERSION"] == (REPO_ROOT / "VERSION").read_text(encoding="ascii").strip()


def test_check_versions_agrees_with_desktop_candidate_validation():
    """The fast gate and the slow desktop gate must never reach different verdicts."""
    assert bump_version.check_versions(REPO_ROOT) == validator.validate_config(REPO_ROOT)[
        "desktop_version"
    ]


def test_tracked_files_cover_every_version_validate_config_checks():
    """A new version-bearing file must not silently escape the fast gate."""
    checked = set(bump_version.VERSION_FILES) | {"gui/src-tauri/tauri.conf.json"}
    source = (REPO_ROOT / "scripts/validate_desktop_candidate.py").read_text(
        encoding="utf-8"
    )
    declared = set(re.findall(r'^\s+"([^"]+)": \w+_version,$', source, re.MULTILINE))

    assert declared - {"VERSION", "codex-instruct.py"} <= checked
    assert checked >= declared


def test_tauri_config_is_not_rewritten_because_it_inherits_the_version():
    assert "gui/src-tauri/tauri.conf.json" not in bump_version.VERSION_FILES

    tauri = json.loads(
        (REPO_ROOT / "gui/src-tauri/tauri.conf.json").read_text(encoding="utf-8")
    )

    assert tauri["version"] == "../package.json"


def test_bump_rewrites_every_tracked_file(tmp_path):
    _repo_fixture(tmp_path)

    result = bump_version.bump(tmp_path, "0.5.0")

    assert result["previous_version"] == "0.4.0"
    assert result["version"] == "0.5.0"
    assert result["changed"] == list(bump_version.VERSION_FILES)
    assert bump_version.read_versions(tmp_path) == {
        relative: "0.5.0" for relative in bump_version.VERSION_FILES
    }


def test_bump_is_byte_reversible(tmp_path):
    _repo_fixture(tmp_path)
    before = {
        relative: (tmp_path / relative).read_bytes()
        for relative in bump_version.VERSION_FILES
    }

    bump_version.bump(tmp_path, "0.5.0")
    bump_version.bump(tmp_path, "0.4.0")

    assert {
        relative: (tmp_path / relative).read_bytes()
        for relative in bump_version.VERSION_FILES
    } == before


def test_bump_preserves_unrelated_lock_entries(tmp_path):
    _repo_fixture(tmp_path)

    bump_version.bump(tmp_path, "0.5.0")

    cargo_lock = (tmp_path / "gui/src-tauri/Cargo.lock").read_text(encoding="utf-8")
    package_lock = json.loads(
        (tmp_path / "gui/package-lock.json").read_text(encoding="utf-8")
    )

    assert 'name = "winapi"\nversion = "0.3.9"' in cargo_lock
    assert package_lock["packages"]["node_modules/left-pad"]["version"] == "1.3.0"
    assert package_lock["lockfileVersion"] == 3


def test_bump_rejects_a_tree_that_already_disagrees(tmp_path):
    """A partial bump must not be silently adopted as the new baseline."""
    _repo_fixture(tmp_path)
    lock = tmp_path / "gui/src-tauri/Cargo.lock"
    lock.write_text(
        lock.read_text(encoding="utf-8").replace(
            'name = "codex-keysmith-gui"\nversion = "0.4.0"',
            'name = "codex-keysmith-gui"\nversion = "0.3.9"',
        ),
        encoding="utf-8",
    )

    with pytest.raises(bump_version.BumpError, match="source versions disagree"):
        bump_version.bump(tmp_path, "0.5.0")

    assert 'version = "0.3.9"' in lock.read_text(encoding="utf-8")


